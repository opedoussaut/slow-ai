#!/usr/bin/env python3
"""Reproducible synthetic benchmark: no-AI rules versus 3-nearest neighbors.

Standard library only. Synthetic labels are policy-generated, not ground truth.
No energy/carbon/cost estimates; latency is locally measured, not cross-machine comparable.
"""
from __future__ import annotations

import argparse
import json
import random
import statistics
import time
from pathlib import Path


def make_data(count: int, seed: int) -> list[dict]:
    rand = random.Random(seed)
    data = []
    for i in range(count):
        row = {
            "id": f"{seed}-{i}",
            "temperature_c": round(40 + rand.random() * 65),
            "vibration_mm_s": round(rand.random() * 16),
            "alarm": rand.random() < 0.09,
        }
        row["expected"] = policy(row)
        data.append(row)
    return data


def policy(row: dict) -> str:
    risk = (
        3 * int(row["alarm"])
        + int(row["temperature_c"] >= 75)
        + int(row["temperature_c"] >= 85)
        + int(row["vibration_mm_s"] >= 7)
        + int(row["vibration_mm_s"] >= 10)
    )
    return "stop" if risk >= 3 else "inspect" if risk >= 1 else "normal"


def rules(row: dict) -> str:
    if row["alarm"] or row["temperature_c"] >= 90 or row["vibration_mm_s"] >= 12:
        return "stop"
    if row["temperature_c"] >= 75 or row["vibration_mm_s"] >= 7:
        return "inspect"
    return "normal"


def distance(a: dict, b: dict) -> float:
    return (
        ((a["temperature_c"] - b["temperature_c"]) / 70) ** 2
        + ((a["vibration_mm_s"] - b["vibration_mm_s"]) / 16) ** 2
        + int(a["alarm"] != b["alarm"])
    )


def predict_knn(row: dict, training: list[dict], k: int = 3) -> str:
    if not training or k < 1:
        raise ValueError("Training data must be nonempty and k must be positive")
    nearest = sorted(training, key=lambda item: (distance(row, item), item["id"]))[:k]
    counts = {label: sum(item["expected"] == label for item in nearest) for label in ("stop", "inspect", "normal")}
    return max(("stop", "inspect", "normal"), key=lambda label: counts[label])


def evaluate(testing: list[dict], predictor, repeats: int) -> dict:
    predictions = [predictor(row) for row in testing]
    correct = sum(pred == row["expected"] for pred, row in zip(predictions, testing))
    # Measure a batch to reduce timer noise; this is wall-clock software timing,
    # not energy or hardware-normalized inference performance.
    timings = []
    for _ in range(repeats):
        start = time.perf_counter_ns()
        for row in testing:
            predictor(row)
        timings.append((time.perf_counter_ns() - start) / len(testing) / 1e6)
    return {
        "correct": correct,
        "total": len(testing),
        "accuracy": correct / len(testing),
        "errors": len(testing) - correct,
        "median_wall_ms_per_case": statistics.median(timings),
        "predictions": [
            {"id": row["id"], "expected": row["expected"], "predicted": pred}
            for row, pred in zip(testing, predictions)
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("challenge/evidence.json"))
    parser.add_argument("--repeats", type=int, default=20)
    args = parser.parse_args()
    if args.repeats < 1:
        parser.error("--repeats must be >= 1")
    training, testing = make_data(180, 202604), make_data(90, 202610)
    result = {
        "experiment": "SlowAI Intelligence Challenge — reproducible Python companion",
        "dataset": "synthetic_policy_generated",
        "train_seed": 202604,
        "test_seed": 202610,
        "training_count": len(training),
        "test_count": len(testing),
        "repeats": args.repeats,
        "results": {
            "deterministic_rules": evaluate(testing, rules, args.repeats),
            "three_nearest_neighbors": evaluate(testing, lambda row: predict_knn(row, training), args.repeats),
        },
        "measurements": {
            "energy_joules": None,
            "carbon_gco2e": None,
            "financial_cost": None,
            "frontier_ai": None,
        },
        "limitations": [
            "Reference labels are generated by a synthetic policy, not independent ground truth.",
            "Timing is local wall-clock time and not comparable across hardware or workloads.",
            "No real-world generalization, energy, carbon, or financial savings claims.",
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(f"Evidence written to {args.output}")
    for name, value in result["results"].items():
        print(f"{name}: {value['accuracy']:.1%} accuracy, median {value['median_wall_ms_per_case']:.5f} ms/case")


if __name__ == "__main__":
    main()
